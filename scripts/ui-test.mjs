// Dev helper: exercise the UI flow (intro → drive → panel) and screenshot each step.
import { chromium, devices } from 'playwright';
const out = process.argv[2];
const mobile = process.argv.includes('--mobile');
const b = await chromium.launch({ args: ['--use-angle=metal', '--enable-gpu', '--ignore-gpu-blocklist'] });
const ctx = mobile ? await b.newContext({ ...devices['iPhone 13'] }) : await b.newContext({ viewport: { width: 1440, height: 900 } });
const p = await ctx.newPage();
const logs = [];
p.on('console', (m) => { if (m.type() === 'error') logs.push(m.text()); });
p.on('pageerror', (e) => logs.push('pageerror: ' + e.message));
await p.goto('http://localhost:5173/', { waitUntil: 'domcontentloaded' });
await p.waitForTimeout(600);
await p.screenshot({ path: `${out}/ui-0-loading.png` });
await p.waitForFunction(() => window.__game?.useGame?.getState().loaded, null, { timeout: 60000 });
await p.waitForTimeout(1500);
await p.screenshot({ path: `${out}/ui-1-intro.png` });
await p.getByRole('button', { name: /Start driving/ }).click();
await p.waitForTimeout(800);
await p.screenshot({ path: `${out}/ui-2-playing.png` });
await p.evaluate(() => window.__game.runtime.teleport(-12.2, -7, 1.57));
await p.waitForTimeout(1500);
await p.screenshot({ path: `${out}/ui-3-prompt.png` });
if (mobile) await p.getByRole('button', { name: /Open About/ }).click(); else await p.keyboard.press('KeyE');
await p.waitForTimeout(1500);
await p.screenshot({ path: `${out}/ui-4-panel.png` });
await p.keyboard.press('Escape');
await p.waitForTimeout(600);
await p.evaluate(() => window.__game.useGame.getState().open('projects', 1));
await p.waitForTimeout(1200);
await p.screenshot({ path: `${out}/ui-5-projects.png` });
await p.keyboard.press('Escape');
await p.waitForTimeout(500);
await p.evaluate(() => window.__game.useGame.getState().open('hero'));
await p.waitForTimeout(1000);
await p.screenshot({ path: `${out}/ui-6-hero.png` });
await p.keyboard.press('Escape');
await p.waitForTimeout(500);
await p.getByRole('button', { name: /Classic view/ }).click();
await p.waitForTimeout(800);
await p.screenshot({ path: `${out}/ui-7-classic.png`, fullPage: false });
console.log(logs.slice(0, 20).join('\n') || 'no errors');
await b.close();
